"""
第一个神经网络：纯 numpy 手写，不需要安装任何东西（numpy 已装在 Anaconda 里）。

任务：教会电脑识别一个非常简单的规律 ——
      y = 2*x + 1 这条直线，让神经网络自己把 "2" 和 "1" 这两个参数学出来。

你会亲眼看到三件 AI 里最核心的事：
  1. 前向传播：用当前权重猜一个答案
  2. 损失函数：衡量猜得有多离谱
  3. 梯度下降：根据"离谱程度"调整权重，一遍遍变准

运行：python 第一个神经网络.py
"""

import numpy as np

# ---------------------------------------------------------------
# 1. 准备"教材"：真实答案就是 y = 2x + 1
# ---------------------------------------------------------------
np.random.seed(42)
x = np.linspace(-1, 1, 100).reshape(-1, 1)   # 100 个输入，取值 -1 到 1
y = 2 * x + 1                                # 真实答案（我们想让机器学会这个）

# ---------------------------------------------------------------
# 2. 初始化权重：一开始完全瞎猜
# ---------------------------------------------------------------
w = np.random.randn(1, 1)   # 权重，真实值应该是 2
b = np.zeros((1, 1))        # 偏置，真实值应该是 1

learning_rate = 0.1         # 学习率：每一步走多大。太大学不会，太小太慢
epochs = 200                # 训练 200 轮

print("训练前： w = %.4f   b = %.4f" % (w.item(), b.item()))
print("-" * 50)

# ---------------------------------------------------------------
# 3. 训练循环：这就是"机器学习"的全过程
# ---------------------------------------------------------------
for epoch in range(epochs):
    # --- 前向传播：用当前权重做预测 ---
    y_pred = x @ w + b              # @ 是矩阵乘法

    # --- 计算损失：均方误差，越小说明猜得越准 ---
    loss = np.mean((y_pred - y) ** 2)

    # --- 反向传播：求损失对 w 和 b 的导数（梯度）---
    # d(loss)/d(w) 和 d(loss)/d(b) 的推导结果如下
    n = x.shape[0]
    grad_w = (2 / n) * x.T @ (y_pred - y)
    grad_b = (2 / n) * np.sum(y_pred - y)

    # --- 梯度下降：朝着让损失变小的方向挪一步 ---
    w = w - learning_rate * grad_w
    b = b - learning_rate * grad_b

    # 每 40 轮打印一次进度
    if epoch % 40 == 0 or epoch == epochs - 1:
        print(f"第 {epoch:3d} 轮   损失 = {loss:.6f}   w = {w.item():.4f}   b = {b.item():.4f}")

print("-" * 50)
print(f"训练后： w = {w.item():.4f}   b = {b.item():.4f}")
print(f"真实值： w = 2.0000   b = 1.0000")
print()

# ---------------------------------------------------------------
# 4. 用训练好的模型预测它没见过的数据
# ---------------------------------------------------------------
print("预测检验（模型没见过这些点）：")
for test_x in [2.0, 5.0, -3.0]:
    pred = (np.array([[test_x]]) @ w + b).item()
    truth = 2 * test_x + 1
    print(f"  x = {test_x:>5}  →  模型预测 {pred:8.4f}   真实答案 {truth:8.4f}")

print()
print("=" * 50)
print("想更深入？试试改这几个地方，观察结果：")
print("  1. 把 learning_rate 改成 1.5  → 看损失怎么爆炸（发散）")
print("  2. 把 learning_rate 改成 0.001 → 看 200 轮够不够")
print("  3. 把 epochs 改成 20 → 看欠拟合长什么样")
print("  4. 把 y 改成 3*x**2 - 2 → 一层网络学不动了，为什么？")
print("     （提示：这时你需要「激活函数」和「多层」，那就是深度学习）")
